// 由 UID 确定性地生成政权名(两到三个音节)。后缀(部/汗国/王国/帝国)由前端按规模与生计决定。
var syl = []string{
	"阿", "巴", "赤", "达", "额", "伏", "嘎", "赫", "伊", "嘉", "喀", "兰", "穆", "纳", "鄂", "帕", "齐", "柔",
	"萨", "塔", "乌", "瓦", "西", "雅", "扎", "昆", "图", "斡", "楚", "罗", "沙", "温", "铁", "白", "青", "玄",
	"金", "云", "河", "岚", "狼", "鹿", "鹰", "熊", "松", "桑", "羌", "夷", "孤", "丹", "苏", "莫", "宁", "安",
	"弥", "库", "勒", "诺", "珂", "琉", "曼", "黎", "焉", "疏", "龟", "姑", "高", "吐", "渤", "靺", "契", "室",
}

func polityName(uid int64) string {
	h := mix(uint64(uid), 0xabcdef)
	n := 2 + int(h%3)/2 // 2 或 3 个音节
	out := ""
	for k := 0; k < n; k++ {
		out += syl[(h>>(8*uint(k+1)))%uint64(len(syl))]
	}
	return out
}
